
import os
import smtplib
import threading
from email.message import EmailMessage
from pathlib import Path

from dotenv import load_dotenv


# Load the .env file from the main project folder.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_ROOT / ".env")


class EmailNotifier:
    """Send JointBank notifications to both account members."""

    def __init__(self, logger=None):
        self.logger = logger

        self.sender = os.getenv("GMAIL_ADDRESS", "").strip()
        self.app_password = os.getenv(
            "GMAIL_APP_PASSWORD", ""
        ).replace(" ", "").strip()

        self.recipients = [
            os.getenv("JOINT_MEMBER_1_EMAIL", "").strip(),
            os.getenv("JOINT_MEMBER_2_EMAIL", "").strip(),
        ]
        self.recipients = [
            email for email in self.recipients if email
        ]

    def _log(self, message):
        if self.logger:
            self.logger.log(f"EMAIL → {message}")

    def configuration_error(self):
        if not self.sender:
            return "GMAIL_ADDRESS is missing from .env."
        if not self.app_password:
            return "GMAIL_APP_PASSWORD is missing from .env."
        if not self.recipients:
            return "Add at least one member email address to .env."
        return None

    def send(self, subject, body):
        """Send one email to the configured joint account members."""
        error = self.configuration_error()
        if error:
            self._log(f"Not sent: {error}")
            return False

        message = EmailMessage()
        message["From"] = self.sender
        message["To"] = ", ".join(self.recipients)
        message["Subject"] = subject
        message.set_content(body)

        try:
            with smtplib.SMTP("smtp.gmail.com", 587, timeout=15) as smtp:
                smtp.ehlo()
                smtp.starttls()
                smtp.ehlo()
                smtp.login(self.sender, self.app_password)
                smtp.send_message(message)

            self._log(
                f"Notification sent to {len(self.recipients)} recipient(s)."
            )
            return True

        except Exception as exc:
            # Never allow an email failure to undo a bank transaction.
            self._log(
                f"Delivery failed ({type(exc).__name__}): {exc}"
            )
            return False

    def send_async(self, subject, body, callback=None):
        """Send email in the background to keep the GUI responsive."""

        def worker():
            success = self.send(subject, body)
            if callback:
                callback(success)

        thread = threading.Thread(target=worker, daemon=True)
        thread.start()
        return thread

    @staticmethod
    def transaction_message(
        transaction_type,
        amount,
        success,
        balance,
        details="",
    ):
        status = "SUCCESSFUL" if success else "FAILED"

        body = (
            "JointBank Transaction Notification\n"
            "----------------------------------\n"
            f"Transaction: {transaction_type}\n"
            f"Amount: INR {amount:,}\n"
            f"Status: {status}\n"
            f"Current displayed balance: INR {balance:,}\n"
        )

        if details:
            body += f"\nDetails: {details}\n"

        body += (
            "\nThis notification was generated by the JointBank "
            "educational simulator, not a real banking service."
        )
        return body
